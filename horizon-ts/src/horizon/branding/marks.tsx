const WORDMARK_BOX = {x: 86, y: 12, width: 174, height: 41}

/** The full-colour mark's shapes, on the 32-unit grid. */
function MarkShapes() {
  return (
    <>
      <Rect width={32} height={32} rx={7} fill={BRAND_COLORS.sky} />
      <Circle cx={10} cy={9} r={4} fill={BRAND_COLORS.sun} />
      <Path d={BACK_HILL} fill={BRAND_COLORS.backHill} />
      <Path d={FRONT_HILL} fill={BRAND_COLORS.frontHill} />
    </>
  )
}

/**
 * The mark. Full colour by default; with `fill`, the one-colour form in that
 * colour (for white-on-colour cards, badges and masks).
 */
export function HorizonMark({
  size,
  fill,
  ...rest
}: {size: number; fill?: string} & Omit<SvgProps, 'fill' | 'width' | 'height'>) {
  return (
    <Svg viewBox="0 0 32 32" width={size} height={size} {...rest}>
      {fill ? (
        <>
          <Circle cx={10} cy={9} r={4} fill={fill} />
          <Path d={MONO_BACK_HILL} fill={fill} />
          <Path d={MONO_FRONT_HILL} fill={fill} />
        </>
      ) : (
        <MarkShapes />
      )}
    </Svg>
  )
}

/** Height over width of the wordmark. */
export const WORDMARK_RATIO = WORDMARK_BOX.height / WORDMARK_BOX.width

/** The "Horizon" wordmark in `fill`. */
export function HorizonWordmark({
  width,
  fill,
  ...rest
}: {width: number; fill: string} & Omit<SvgProps, 'fill' | 'width' | 'height'>) {
  const {x, y, width: w, height: h} = WORDMARK_BOX
  return (
    <Svg
      viewBox={`${x} ${y} ${w} ${h}`}
      width={width}
      height={width * WORDMARK_RATIO}
      {...rest}>
      <Path d={WORDMARK} fill={fill} />
    </Svg>
  )
}

/** Height over width of the lockup. */
export const LOCKUP_RATIO = 64 / 264

/** The lockup: the full-colour mark beside the wordmark in `fill`. */
export function HorizonLockup({
  width,
  fill,
  ...rest
}: {width: number; fill: string} & Omit<SvgProps, 'fill' | 'width' | 'height'>) {
  return (
    <Svg
      viewBox="0 0 264 64"
      width={width}
      height={width * LOCKUP_RATIO}
      {...rest}>
      <G transform="scale(2)">
        <MarkShapes />
      </G>
      <Path d={WORDMARK} fill={fill} />
    </Svg>
  )
}
