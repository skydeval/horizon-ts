/*
 * Builds the Android app's JavaScript copy of kryphocron-web's encoder from
 * binaryen's wasm2js output and the vendored glue. See
 * vendor/kryphocron-web/VERSION.md ("JavaScript build for native").
 *
 *   node scripts/kryphocron-native.mjs <wasm2js output> <vendor dir>
 *
 * Writes into <vendor dir>:
 * - kryphocron_web_bg.wasm2js.js: the module, exporting `instantiate(imports)`
 *   in place of wasm2js's own import and exports;
 * - kryphocron_web_native.js: the glue with its two memory caches checked
 *   against the current buffer. A WebAssembly memory detaches its old buffer
 *   when it grows, which is what the glue looks for; wasm2js's memory swaps
 *   in a new one instead, so without this the glue reads stale memory once a
 *   long post grows it.
 *
 * Every replacement must match exactly once, or nothing is written.
 */

import {readFileSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'

const [rawPath, vendorDir] = process.argv.slice(2)
if (!rawPath || !vendorDir) {
  console.error(
    'usage: node scripts/kryphocron-native.mjs <wasm2js output> <vendor dir>',
  )
  process.exit(2)
}

function replaceOnce(source, from, to, what) {
  const at = source.indexOf(from)
  if (at === -1 || source.indexOf(from, at + 1) !== -1) {
    throw new Error(`${what}: expected exactly one match`)
  }
  return source.slice(0, at) + to + source.slice(at + from.length)
}

// The module.
let module = readFileSync(rawPath, 'utf8')
const head =
  "import * as $_kryphocron_web_bg_js from './kryphocron_web_bg.js';\n"
if (!module.startsWith(head)) throw new Error('module: unexpected first line')
module = module.slice(head.length)
const tailAt = module.indexOf('var retasmFunc = asmFunc({')
if (tailAt === -1) throw new Error('module: no retasmFunc')
if (/\blaquna\b/i.test(module))
  throw new Error('module: names the codec in plain text')
module =
  `/* eslint-disable */
/*
 * kryphocron-web's encoder as plain JavaScript, for the Android app, whose
 * engine (Hermes) has no WebAssembly. Generated by
 * scripts/kryphocron-native.mjs; do not edit. See VERSION.md. MPL-2.0, like
 * the .wasm it was converted from.
 */
` +
  module.slice(0, tailAt) +
  `/**
 * The module's exports over the glue's imports, as a WebAssembly.Instance's
 * would be.
 */
export function instantiate(imports) {
  return asmFunc(imports);
}
`

// The glue.
let glue = readFileSync(join(vendorDir, 'kryphocron_web.js'), 'utf8')
glue = replaceOnce(
  glue,
  'if (cachedDataViewMemory0 === null || cachedDataViewMemory0.buffer.detached === true || (cachedDataViewMemory0.buffer.detached === undefined && cachedDataViewMemory0.buffer !== wasm.memory.buffer)) {',
  'if (cachedDataViewMemory0 === null || cachedDataViewMemory0.buffer !== wasm.memory.buffer) {',
  'glue: DataView cache',
)
glue = replaceOnce(
  glue,
  'if (cachedUint8ArrayMemory0 === null || cachedUint8ArrayMemory0.byteLength === 0) {',
  'if (cachedUint8ArrayMemory0 === null || cachedUint8ArrayMemory0.buffer !== wasm.memory.buffer) {',
  'glue: Uint8Array cache',
)
// The async init's default path is the web's; the app calls initSync only,
// and a bundle for native may not accept `import.meta`.
glue = replaceOnce(
  glue,
  "module_or_path = new URL('kryphocron_web_bg.wasm', import.meta.url);",
  "throw new Error('kryphocron-web: on native, use initSync');",
  'glue: default path',
)
glue = replaceOnce(
  glue,
  '/* @ts-self-types="./kryphocron_web.d.ts" */',
  `/* @ts-self-types="./kryphocron_web_native.d.ts" */
/*
 * kryphocron_web.js for the Android app's JavaScript encoder: the memory
 * caches compare against the current buffer, and the async init's web path
 * is gone. Generated by scripts/kryphocron-native.mjs; do not edit. See
 * VERSION.md.
 */`,
  'glue: types header',
)

const moduleTypes = `/* Generated by scripts/kryphocron-native.mjs; do not edit. */
/**
 * The encoder module's exports (memory, preparePrivatePost and the glue's
 * helpers) over the glue's imports, keyed by module name.
 */
export function instantiate(
  imports: Record<string, Record<string, unknown>>,
): Record<string, unknown>
`
const glueTypes = readFileSync(join(vendorDir, 'kryphocron_web.d.ts'), 'utf8')

writeFileSync(join(vendorDir, 'kryphocron_web_bg.wasm2js.js'), module)
writeFileSync(join(vendorDir, 'kryphocron_web_bg.wasm2js.d.ts'), moduleTypes)
writeFileSync(join(vendorDir, 'kryphocron_web_native.js'), glue)
writeFileSync(join(vendorDir, 'kryphocron_web_native.d.ts'), glueTypes)
console.log(
  'wrote kryphocron_web_bg.wasm2js.js, kryphocron_web_native.js and their .d.ts',
)
