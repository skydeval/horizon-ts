/* oxlint-disable import/no-nodejs-modules -- This CLI writes key files with Node APIs. */
/*
 * Horizon: the OAuth client signing key (confidential client).
 *
 *   node scripts/horizon-oauth-key.js generate <dir>
 *     makes a new P-256 key. The private half goes only to
 *     <dir>/oauth-client-key.secret.json (mode 600, never overwritten), in
 *     the shape `wrangler pages secret bulk` reads:
 *     {"HORIZON_OAUTH_CLIENT_KEY": "<private JWK>"}. Prints the public half.
 *
 *   node scripts/horizon-oauth-key.js public '<public JWK>'
 *     writes the public half into the repo: public/oauth/jwks.json (served
 *     at nearhorizon.app/oauth/jwks.json) and
 *     src/horizon/session/oauth-signing-key.generated.ts (the app's copy).
 *     Refuses anything with a private part.
 *
 * The private key never passes through the repo, a log or the screen.
 */

const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.join(__dirname, '..')
const JWKS = path.join(ROOT, 'public', 'oauth', 'jwks.json')
const GENERATED = path.join(
  ROOT,
  'src',
  'horizon',
  'session',
  'oauth-signing-key.generated.ts',
)
const SECRET_FILE = 'oauth-client-key.secret.json'
const PUBLIC_FIELDS = ['kty', 'crv', 'x', 'y']

/**
 * The public JWK the repo keeps, in a fixed key order.
 *
 * @param {Record<string, unknown>} jwk
 */
function publicJwk(jwk) {
  if (jwk.d !== undefined) throw new Error('refusing a private key')
  if (jwk.kty !== 'EC' || jwk.crv !== 'P-256') {
    throw new Error('expected a P-256 key')
  }
  if (typeof jwk.kid !== 'string' || !/^[a-z0-9-]{1,64}$/.test(jwk.kid)) {
    throw new Error('expected a kid of lower-case letters, digits and -')
  }
  /** @type {Record<string, string>} */
  const out = {}
  for (const field of PUBLIC_FIELDS) {
    if (typeof jwk[field] !== 'string') throw new Error(`missing ${field}`)
    out[field] = jwk[field]
  }
  return {...out, kid: jwk.kid, alg: 'ES256', use: 'sig'}
}

function renderJwks(jwk) {
  return `${JSON.stringify({keys: [jwk]}, null, 2)}\n`
}

function renderGenerated(jwk) {
  return [
    '/*',
    ' * Generated by scripts/horizon-oauth-key.js; do not edit. The public half',
    " * of Horizon's OAuth client signing key, also served as",
    ' * public/oauth/jwks.json.',
    ' */',
    '',
    `export const OAUTH_SIGNING_KEY = ${JSON.stringify(jwk, null, 2)} as const`,
    '',
  ].join('\n')
}

async function generate(dir) {
  const target = path.join(path.resolve(dir), SECRET_FILE)
  if (fs.existsSync(target)) {
    throw new Error(`${target} exists; move it away to make a new key`)
  }
  const pair = await crypto.subtle.generateKey(
    {name: 'ECDSA', namedCurve: 'P-256'},
    true,
    ['sign', 'verify'],
  )
  const priv = await crypto.subtle.exportKey('jwk', pair.privateKey)
  const day = new Date().toISOString().slice(0, 10).replace(/-/g, '')
  const kid = `horizon-${day}`
  const secret = {
    kty: priv.kty,
    crv: priv.crv,
    x: priv.x,
    y: priv.y,
    d: priv.d,
    kid,
  }
  fs.mkdirSync(path.dirname(target), {recursive: true})
  fs.writeFileSync(
    target,
    `${JSON.stringify({HORIZON_OAUTH_CLIENT_KEY: JSON.stringify(secret)})}\n`,
    {mode: 0o600, flag: 'wx'},
  )
  const pub = publicJwk({
    kty: priv.kty,
    crv: priv.crv,
    x: priv.x,
    y: priv.y,
    kid,
  })
  console.log(JSON.stringify(pub))
}

function writePublic(raw) {
  const jwk = publicJwk(JSON.parse(raw))
  fs.mkdirSync(path.dirname(JWKS), {recursive: true})
  fs.writeFileSync(JWKS, renderJwks(jwk))
  fs.writeFileSync(GENERATED, renderGenerated(jwk))
  console.log(
    `wrote ${path.relative(ROOT, JWKS)} and ${path.relative(ROOT, GENERATED)} for ${jwk.kid}`,
  )
}

async function main(argv) {
  const [command, arg] = argv
  if (command === 'generate' && arg) return generate(arg)
  if (command === 'public' && arg) return writePublic(arg)
  throw new Error(
    "usage: horizon-oauth-key.js generate <dir> | public '<public JWK>'",
  )
}

if (require.main === module) {
  main(process.argv.slice(2)).catch(error => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}

module.exports = {publicJwk, renderJwks, renderGenerated}
